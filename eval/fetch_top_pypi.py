"""Fetch the PyPI popular-name snapshot for the typosquat check. ONLINE — by hand.

    uv run python -m eval.fetch_top_pypi --dry-run
    uv run python -m eval.fetch_top_pypi --count 5000

Source: hugovk/top-pypi-packages, a monthly dump of the most-downloaded PyPI
projects over the last 30 days, derived from the public PyPI download statistics
on BigQuery. One JSON file, project names and download counts only.

The file it writes replaces the hand-seeded reference set in engine/data/. Its
header records the source URL, the fetch date and the row count, so the snapshot
the benchmark used can always be identified. Once a real snapshot is in place,
raise MIN_SNAPSHOT_NAMES in engine/checks.py to TARGET_MIN_NAMES below: the
check fails closed on a reference set too small to judge a near-miss, and the
hand-seeded files would otherwise keep that bar on the floor.
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

import httpx
from contracts.contracts import Ecosystem
from engine.checks import normalize_name

DATA_DIR = Path(__file__).resolve().parent.parent / "engine" / "data"

SOURCE_URL = (
    "https://raw.githubusercontent.com/hugovk/top-pypi-packages/main/"
    "top-pypi-packages-30-days.min.json"
)
SOURCE_PAGE = "https://github.com/hugovk/top-pypi-packages"

# What MIN_SNAPSHOT_NAMES in engine/checks.py should become once this has run.
TARGET_MIN_NAMES = 4000

TIMEOUT = httpx.Timeout(connect=5.0, read=30.0, write=5.0, pool=5.0)
HEADERS = {"User-Agent": "InstallGate/0.1 (typosquat reference snapshot)"}


def extract_rows(payload: object) -> tuple[list[dict[str, object]], str | None]:
    """Rows plus the dump's own last_update, if it reports one.

    The dump has moved key names between releases, so accept the known shapes.
    """
    last_update: str | None = None
    rows: list[dict[str, object]] = []
    if isinstance(payload, dict):
        raw_update = payload.get("last_update") or payload.get("last_updated")
        last_update = str(raw_update) if raw_update else None
        for key in ("rows", "data", "packages"):
            value = payload.get(key)
            if isinstance(value, list):
                rows = [r for r in value if isinstance(r, dict)]
                break
    elif isinstance(payload, list):
        rows = [r for r in payload if isinstance(r, dict)]
    return rows, last_update


def _downloads(row: dict[str, object]) -> int:
    for key in ("download_count", "downloads", "count"):
        value = row.get(key)
        if isinstance(value, int):
            return value
        if isinstance(value, str) and value.isdigit():
            return int(value)
    return 0


def _name(row: dict[str, object]) -> str | None:
    for key in ("project", "name", "package"):
        value = row.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def extract_names(payload: object) -> tuple[list[str], str | None]:
    """Normalised project names, most downloaded first, deduplicated.

    Sorting is explicit rather than trusting the file's order, and names go
    through the same PEP 503 normalisation the check applies, so the snapshot
    and the lookup agree on what `Requests_OAuthlib` is called. Normalisation
    merges spellings, so dedupe afterwards and keep the most-downloaded one.
    """
    rows, last_update = extract_rows(payload)
    ordered = sorted(rows, key=_downloads, reverse=True)

    names: list[str] = []
    seen: set[str] = set()
    for row in ordered:
        raw = _name(row)
        if raw is None:
            continue
        name = normalize_name(raw, Ecosystem.PYPI)
        if name and name not in seen:
            seen.add(name)
            names.append(name)
    return names, last_update


def render(names: list[str], count: int, stamp: str, last_update: str | None) -> str:
    header = [
        "# PyPI popular-name reference set for the typosquat check (rules P4, P5).",
        "#",
        f"# Source:        {SOURCE_PAGE}",
        f"# File:          {SOURCE_URL}",
        f"# Source dated:  {last_update or 'not reported by the source'}",
        f"# Fetched:       {stamp}",
        f"# Names:         {count}, most downloaded first, PEP 503 normalised, deduplicated",
        "#",
        "# Generated by `uv run python -m eval.fetch_top_pypi`. Do not hand-edit:",
        "# a name added by hand becomes a canonical spelling the check trusts.",
        "# Re-fetch and commit the whole file instead, keeping this header.",
    ]
    return "\n".join(header) + "\n" + "\n".join(names[:count]) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=5000)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="defaults to engine/data/pypi-top<count>-<date>.txt",
    )
    args = parser.parse_args()

    stamp = datetime.now(UTC).strftime("%Y-%m-%d")

    if args.dry_run:
        print(f"would GET {SOURCE_URL}")
        print(f"would keep the top {args.count} names")
        print(f"would write {args.out or DATA_DIR / f'pypi-top{args.count}-{stamp}.txt'}")
        return 0

    response = httpx.get(SOURCE_URL, timeout=TIMEOUT, headers=HEADERS, follow_redirects=True)
    response.raise_for_status()
    names, last_update = extract_names(response.json())

    if len(names) < args.count:
        print(
            f"source returned {len(names)} names, fewer than the {args.count} requested; "
            "not writing a snapshot that would silently under-cover the check"
        )
        return 1

    out = args.out or DATA_DIR / f"pypi-top{args.count}-{stamp}.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(names, args.count, stamp, last_update), encoding="utf-8")

    print(f"wrote {args.count} names -> {out}")
    print("next:")
    print(f"  1. point _SNAPSHOTS[Ecosystem.PYPI] in engine/checks.py at {out.name}")
    print(f"  2. raise MIN_SNAPSHOT_NAMES to {TARGET_MIN_NAMES}")
    print("  3. delete the hand-seeded pypi-top5k-2026-10-25.txt")
    print("  4. rerun the benchmark; typosquat cases are re-judged against real names")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
